"""Synthetic routing traces calibrated to the shipped per-layer statistics.

The real traces (results/traces/*.npz) are not in the repo. This writes
build.npz / holdout.npz in the same key layout so experiments/sim_paging.py
runs unchanged, generated by a per-layer model fitted to results/*.json:

  * popularity : Zipf over 512 experts with a per-layer exponent s_li,
                 fitted so a build-split top-14 "prior" set covers the
                 same fraction of holdout top-10 routing as
                 results/ple_probe.json reports for that layer
                 (0.11 .. 0.26 across layers).
  * persistence: each expert used at token t-1 is kept at t with
                 probability p_li, fitted so |S_t & S_{t-1}|/10 matches the
                 per-layer "prev" coverage in results/trigger_eval.json
                 (0.06 .. 0.51 across layers).
  * topic shift: per prompt, every expert's weight is multiplied by a
                 lognormal factor exp(beta * N(0,1)); per split, by
                 exp(shift * N(0,1)). beta and shift are global knobs
                 chosen by experiments/synth_validate.py so plain LRU and
                 pinned-hot-set served fractions land near the shipped
                 table (results/sim_paging.json).

The synthetic trace reproduces aggregate statistics, not the real
token-level structure (prefill bursts, prompt boundaries, cross-layer
correlation). Treat conclusions drawn on it as directional.

usage: .venv/bin/python experiments/synth_trace.py --beta 2.0 --shift 0.3
"""
import argparse, json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
L, K, E = 48, 10, 512
BUDGET = 14


def gumbel_topk(logw, k, rng):
    """rows of logw [N,E] -> [N,k] indices sampled w/o replacement ∝ w,
    in sampling order (Gumbel-top-k)."""
    g = logw - np.log(-np.log(rng.random(logw.shape)))
    top = np.argpartition(-g, k - 1, axis=1)[:, :k]
    order = np.argsort(-np.take_along_axis(g, top, axis=1), axis=1)
    return np.take_along_axis(top, order, axis=1)


def zipf_logw(s):
    return -s * np.log(np.arange(1, E + 1))


def mc_prior14(s, beta, shift, rng, n=600):
    """fraction of a holdout top-10 covered by the build top-14 prior."""
    base = zipf_logw(s)
    build = base + shift * rng.standard_normal(E)
    hold = base + shift * rng.standard_normal(E)
    top14 = set(np.argsort(-build)[:BUDGET].tolist())
    logw = hold[None, :] + beta * rng.standard_normal((n, E))
    draws = gumbel_topk(logw, K, rng)
    hit = sum(len(top14 & set(r.tolist())) for r in draws)
    return hit / (n * K)


def mc_prev(s, beta, p, rng, n=400):
    """|S_t & S_{t-1}|/K for one prompt of n tokens."""
    logw = zipf_logw(s) + beta * rng.standard_normal(E)
    prev = gumbel_topk(logw[None, :], K, rng)[0]
    hits = 0
    for _ in range(n):
        cur = step(logw[None, :], prev[None, :], np.array([p]), rng)[0]
        hits += len(set(cur.tolist()) & set(prev.tolist()))
        prev = cur
    return hits / (n * K)


def step(logw, prev, p, rng):
    """one token for a batch of layers: logw [B,E], prev [B,K], p [B]."""
    B = logw.shape[0]
    keep = rng.random((B, K)) < p[:, None]
    fresh = gumbel_topk(logw, 2 * K, rng)            # [B,2K] in order
    out = np.zeros((B, K), np.int64)
    for b in range(B):
        kept = prev[b][keep[b]]
        ks = set(kept.tolist())
        fill = [e for e in fresh[b].tolist() if e not in ks][:K - len(kept)]
        out[b] = np.concatenate([kept, np.array(fill, np.int64)])
    return out


def bisect(f, target, lo, hi, iters=14):
    for _ in range(iters):
        mid = 0.5 * (lo + hi)
        if f(mid) < target:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def fit_layers(prior14, prev, beta, shift, rng):
    s_li, p_li, got_prior, got_prev = [], [], [], []
    for li in range(L):
        r1 = np.random.default_rng(rng.integers(1 << 31))
        s = bisect(lambda s: mc_prior14(s, beta, shift,
                                        np.random.default_rng(r1.integers(1 << 31))),
                   prior14[li], 0.05, 2.0)
        r2 = np.random.default_rng(rng.integers(1 << 31))
        p = bisect(lambda p: mc_prev(s, beta, p,
                                     np.random.default_rng(r2.integers(1 << 31))),
                   prev[li], 0.0, 0.98, iters=10)
        s_li.append(s); p_li.append(p)
        got_prior.append(mc_prior14(s, beta, shift, np.random.default_rng(li)))
        got_prev.append(mc_prev(s, beta, p, np.random.default_rng(li)))
    return s_li, p_li, got_prior, got_prev


def gen_split(split, n_prompts, total_rows, s_li, p_li, beta, shift,
              perm, rng, feat_dim, codebook, feat_noise):
    base = np.stack([zipf_logw(s)[perm[li]] for li, s in enumerate(s_li)])
    split_shift = base + shift * rng.standard_normal((L, E))
    lens = rng.multinomial(total_rows - 40 * n_prompts,
                           np.ones(n_prompts) / n_prompts) + 40
    recs = {}
    p = np.array(p_li)
    for pi in range(n_prompts):
        T = int(lens[pi])
        logw = split_shift + beta * rng.standard_normal((L, E))
        idx = np.zeros((T, L, K), np.int16)
        prev = gumbel_topk(logw, K, rng)
        for t in range(T):
            cur = prev if t == 0 else step(logw, prev, p, rng)
            idx[t] = cur
            prev = cur
        sc = rng.dirichlet(np.ones(K) * 2.0, size=(T, L)).astype(np.float16)
        # features: sum of per-layer codebook rows of the gold experts
        feat = np.zeros((T, feat_dim), np.float32)
        for li in range(L):
            feat += codebook[li][idx[:, li].astype(np.int64)].sum(1)
        feat /= np.sqrt(L * K)
        feat += feat_noise * rng.standard_normal(feat.shape).astype(np.float32)
        tag = f"p{pi}_{split}{pi}"
        recs[f"{tag}|ids"] = rng.integers(0, 150000, size=T + 1)
        recs[f"{tag}|PLE_ngram"] = feat.astype(np.float16)
        for li in range(L):
            recs[f"{tag}|L{li}_idx"] = idx[:, li]
            recs[f"{tag}|L{li}_score"] = sc[:, li]
    return recs, lens


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--beta", type=float, default=2.0)
    ap.add_argument("--shift", type=float, default=0.3)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--build-rows", type=int, default=3747)
    ap.add_argument("--holdout-rows", type=int, default=2882)
    ap.add_argument("--n-build", type=int, default=17)
    ap.add_argument("--n-holdout", type=int, default=13)
    ap.add_argument("--feat-dim", type=int, default=256)
    ap.add_argument("--feat-noise", type=float, default=1.0)
    ap.add_argument("--out-dir", default=str(ROOT / "results/traces_synth"))
    a = ap.parse_args()

    probe = json.load(open(ROOT / "results/ple_probe.json"))["per_layer"]
    trig = json.load(open(ROOT / "results/trigger_eval.json"))["by_layer"]
    prior14 = [probe[str(li)]["prior"] for li in range(L)]
    prev = [trig[str(li)]["prev"] for li in range(L)]

    rng = np.random.default_rng(a.seed)
    s_li, p_li, got_prior, got_prev = fit_layers(prior14, prev, a.beta,
                                                 a.shift, rng)
    perm = [rng.permutation(E) for _ in range(L)]
    codebook = rng.standard_normal((L, E, a.feat_dim)).astype(np.float32)
    out = Path(a.out_dir); out.mkdir(parents=True, exist_ok=True)
    for split, n, rows in (("build", a.n_build, a.build_rows),
                           ("holdout", a.n_holdout, a.holdout_rows)):
        recs, lens = gen_split(split, n, rows, s_li, p_li, a.beta, a.shift,
                               perm, rng, a.feat_dim, codebook, a.feat_noise)
        np.savez_compressed(out / f"{split}.npz", **recs)
        print(f"{split}: {n} prompts, rows={int(lens.sum())} "
              f"(min {lens.min()} max {lens.max()})")
    calib = dict(config=vars(a),
                 per_layer={li: dict(s=round(s_li[li], 3), p=round(p_li[li], 3),
                                     prior14_target=prior14[li],
                                     prior14_fit=round(got_prior[li], 3),
                                     prev_target=prev[li],
                                     prev_fit=round(got_prev[li], 3))
                            for li in range(L)},
                 overall=dict(prior14_target=float(np.mean(prior14)),
                              prior14_fit=float(np.mean(got_prior)),
                              prev_target=float(np.mean(prev)),
                              prev_fit=float(np.mean(got_prev))))
    (out / "calibration.json").write_text(json.dumps(calib, indent=1))
    print("fit  prior@14 target %.3f got %.3f | prev target %.3f got %.3f"
          % (np.mean(prior14), np.mean(got_prior), np.mean(prev),
             np.mean(got_prev)))
    print("s range %.2f..%.2f  p range %.2f..%.2f" %
          (min(s_li), max(s_li), min(p_li), max(p_li)))


if __name__ == "__main__":
    main()
